import pandas as pd
import matplotlib.pyplot as plt

pl = pd.read_csv("players_data-2025_2026.csv")

pl = pl[~pl["Pos"].str.contains("GK", na=False)].copy()

pl["Primary_Pos"] = pl["Pos"].str.split(",").str[0]
pl["Secondary_Pos"] = pl["Pos"].str.split(",").str[1]

pl = pl[pl["Min"] >= 900].copy()

pl["Transfered?"] = pl.duplicated(["Player", "Born"], keep=False)

count_stats = [
    "MP", "Starts", "Min", "90s",
    "Gls", "Ast", "xG", "xAG", "npxG", "G-PK",
    "Tkl", "TklW", "Blocks", "Int", "Clr",
    "PrgP", "PrgC", "KP", "xA", "PPA",
    "Touches", "Carries", "Mis", "Dis",
    "CrdY", "CrdR", "Recov"
]

count_stats = [col for col in count_stats if col in pl.columns]

totals = pl.groupby(["Player", "Born"])[count_stats].sum(min_count=1)

pl = pl.drop_duplicates(["Player", "Born"], keep="last")
pl = pl.drop(columns=count_stats)
pl = pl.merge(totals, on=["Player", "Born"], how="left")

fw_features = ["G-PK", "Ast", "Sh", "SoT", "Off"]
mf_features = ["Ast", "Sh", "TklW", "Int", "Crs"]
df_features = ["TklW", "Int", "Fls", "Crs", "Fld"]

feature_stats = list(dict.fromkeys(
    fw_features + mf_features + df_features
))

pl = pl[pl["90s"] > 0].copy()

for col in feature_stats:
    pl[col + "_p90"] = pl[col] / pl["90s"]

info = [
    "Player", "Born", "Nation", "Age",
    "Squad", "Comp", "Pos",
    "Primary_Pos", "Secondary_Pos",
    "Transfered?", "Min", "90s"
]

pl = pl[info + [col + "_p90" for col in feature_stats]].copy()

pl.to_csv("players_cleaned.csv", index=False)

forwards = pl[
    (pl["Primary_Pos"] == "FW") |
    (pl["Secondary_Pos"] == "FW")
]

plt.hist(forwards["Sh_p90"].dropna(), bins=20, edgecolor="black")
plt.xlabel("Shots per 90 Minutes")
plt.ylabel("Number of Players")
plt.title("Distribution of Shots per 90 — Forwards")
plt.show()

plt.scatter(forwards["Sh_p90"], forwards["SoT_p90"], alpha=0.6)
plt.xlabel("Shots per 90 Minutes")
plt.ylabel("Shots on Target per 90 Minutes")
plt.title("Shots vs. Shots on Target — Forwards")
plt.show()

fw_tkl = pl[
    (pl["Primary_Pos"] == "FW") |
    (pl["Secondary_Pos"] == "FW")
]["TklW_p90"].dropna()

mf_tkl = pl[
    (pl["Primary_Pos"] == "MF") |
    (pl["Secondary_Pos"] == "MF")
]["TklW_p90"].dropna()

df_tkl = pl[
    (pl["Primary_Pos"] == "DF") |
    (pl["Secondary_Pos"] == "DF")
]["TklW_p90"].dropna()

plt.boxplot(
    [fw_tkl, mf_tkl, df_tkl],
    tick_labels=["Forwards", "Midfielders", "Defenders"]
)

plt.ylabel("Tackles Won per 90 Minutes")
plt.title("Tackles Won per 90 by Position")
plt.show()

print("Dataset shape:", pl.shape)
print("Missing values:")
print(pl.isnull().sum())

for pos in ["FW", "MF", "DF"]:
    print(pos, (pl["Primary_Pos"] == pos).sum())

print("Transferred players:", pl["Transfered?"].sum())