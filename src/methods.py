import numpy as np

#Function 1: Sample Mean
def my_mean(x):
  return np.sum(x, axis=0) / len(x)
#Function 2: Mean Centering
def my_center(x,mu_hat):
  return x-mu_hat
#Function 3: Maximum Likelihood Covariance Estimator
def my_covariance(x_centered):
  n=len(x_centered)
  return np.dot(x_centered.T, x_centered) / (n)
#Function 4: Maximum Likelihood Covariance Estimator
def my_inverse(sigma):
  d=len(sigma)
  a=np.column_stack((sigma,np.eye(d))).astype(float)
  for i in range(d):
    a[i]=a[i]/a[i,i]
    for j in range(d):
      if i !=j:
        a[j]=a[j]-a[j,i]*a[i]
  return a[:,d:]
#Function 5: Squared Mahalanobis Distance
def my_mahalanobis2(x,mu,sigma_inv):
  diff=x-mu
  return np.sum(np.dot(diff,sigma_inv)*diff,axis=1)
from scipy.stats import chi2
#Function 6: Chi-Squared Quantile Threshold
def my_threshold(d,alpha):
  return chi2.ppf(1-alpha,d)
#Function 7: Anomaly Classification
def my_anomalies(d2, tau):
  return d2 > tau