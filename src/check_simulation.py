import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import chi2

from simulate import simulate_normal
from methods import (
    my_mean, my_center, my_covariance, my_inverse,
    my_mahalanobis2, my_threshold, my_anomalies
)

n = 5000
d = 5

x, mu, sigma = simulate_normal(n=5000, seed=2026)

print("Simulated dataset shape:", x.shape)
print("First five observations:")
print(x[:5])

mu_hat = np.mean(x, axis=0)
centered = x - mu_hat
sigma_hat = np.dot(centered.T, centered) / n

print("True mean:", mu)
print("Estimated mean:", mu_hat)
print("True covariance:")
print(sigma)
print("Estimated covariance:")
print(sigma_hat)

eigenvalues, Q = np.linalg.eigh(sigma)
Lambda_inv_sqrt = np.diag(1 / np.sqrt(eigenvalues))
Sigma_inv_sqrt = np.dot(
    np.dot(Q, Lambda_inv_sqrt), Q.T
)

z = np.dot(x - mu, Sigma_inv_sqrt)
z_cov = np.cov(z, rowvar=False, bias=True)

print("Whitened covariance:")
print(z_cov)
print("Expected covariance:")
print(np.eye(d))

Sigma_inv = np.linalg.inv(sigma)
centered = x - mu

D2 = np.sum(
    np.dot(centered, Sigma_inv) * centered,
    axis=1
)

print("Minimum squared distance:", np.min(D2))
print("Simulated mean:", np.mean(D2))
print("Theoretical mean:", d)
print("Simulated variance:", np.var(D2))
print("Theoretical variance:", 2 * d)

alpha = 0.01
threshold = chi2.ppf(1 - alpha, d)
anomalies = D2 > threshold
observed_rate = np.mean(anomalies)

print("Theoretical threshold:", threshold)
print("Expected false-alarm rate:", alpha)
print("Observed false-alarm rate:", observed_rate)
print("Number of flagged observations:", np.sum(anomalies))

