sigma_inv = my_inverse(sigma_hat)
sigma_inv_lib = np.linalg.inv(sigma_hat)
inverse_error = np.max(np.abs(sigma_inv - sigma_inv_lib))

print("Maximum inverse error:", inverse_error)

d2 = my_mahalanobis2(x, mu_hat, sigma_inv)
