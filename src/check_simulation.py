sizes = [100, 1000, 10000]
mean_errors = []
cov_errors = []

for n in sizes:
    rng = np.random.default_rng(0)
    x_sim = rng.multivariate_normal(mu, sigma, size=n)

    mu_est = my_mean(x_sim)
    x_centered = my_center(x_sim, mu_est)
    sigma_est = my_covariance(x_centered)

    mean_errors.append(np.max(np.abs(mu_est - mu)))
    cov_errors.append(np.max(np.abs(sigma_est - sigma)))

print("Sample sizes:", sizes)
print("Mean errors:", mean_errors)
print("Covariance errors:", cov_errors)

plt.plot(sizes, mean_errors, marker='o', label='Mean Error')
plt.plot(sizes, cov_errors, marker='o', label='Covariance Error')
plt.xscale('log')
plt.yscale('log')
plt.xlabel('Sample Size (n)')
plt.ylabel('Maximum Absolute Error')
plt.title('Estimation Error vs. Sample Size')
